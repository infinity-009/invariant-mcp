from __future__ import annotations

from pathlib import Path

from invariant_mcp.rules import ALL_RULES


class AgentRuleCompiler:
    """Compiles canonical repository safety invariants across OpenAI Codex, Claude Code, Gemini, and Cursor."""

    TARGETS = ("AGENTS.md", "CLAUDE.md", "GEMINI.md", ".cursorrules")

    def __init__(self, workspace_root: Path | None = None) -> None:
        self.workspace_root = (workspace_root or Path.cwd()).resolve()

    def render_markdown(self, agent_name: str) -> str:
        rule_lines: list[str] = [
            f"- **`{r.rule_id}` ({r.severity.value.upper()}) — {r.name}**: {r.description}"
            for r in ALL_RULES
        ]
        joined_rules = "\n".join(rule_lines)
        return (
            f"# {agent_name} Safety & Verification Invariants\n\n"
            "Generated by `invariant-mcp`. Run pre-flight checks before staging or committing code.\n\n"
            "## Mandatory Workflow Gates\n"
            "1. **Pre-Flight Static Gate**: Run `invariant-gate check .` (or call MCP `preflight_scan_repo`) before commits.\n"
            "2. **Cryptographic Test Proof**: Run `invariant-gate verify \"pytest\"` (or call MCP `verify_command_with_receipt`) to generate a SHA-256/HMAC receipt.\n"
            "3. **Human Consent for Remote Mutations**: Never run `git push` or create remote pull requests without explicit user approval.\n\n"
            "## Enforced Production Invariants\n"
            f"{joined_rules}\n"
        )

    def sync_all(self) -> dict[str, str]:
        written: dict[str, str] = {}
        mapping = {
            "AGENTS.md": "OpenAI Codex & Universal Agent",
            "CLAUDE.md": "Claude Code",
            "GEMINI.md": "Gemini & Antigravity",
            ".cursorrules": "Cursor IDE",
        }
        for filename, title in mapping.items():
            dest = self.workspace_root / filename
            dest.write_text(self.render_markdown(title), encoding="utf-8")
            written[filename] = str(dest)
        return written
